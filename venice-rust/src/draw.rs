pub struct Canvas { pub w: i32, pub h: i32, pub px: Vec<u32> }

impl Canvas {
    pub fn new(w: i32, h: i32) -> Canvas { Canvas { w, h, px: vec![0u32; (w * h) as usize] } }
    pub fn clear(&mut self) { for p in self.px.iter_mut() { *p = 0; } }

    #[inline]
    pub fn blend(&mut self, x: i32, y: i32, r: u8, g: u8, b: u8, a: u8) {
        if x < 0 || y < 0 || x >= self.w || y >= self.h || a == 0 { return; }
        let i = (y * self.w + x) as usize;
        let sa = a as u32;
        let ia = 255 - sa;
        let d = self.px[i];
        let da = (d >> 24) & 0xFF;
        let dr = (d >> 16) & 0xFF;
        let dg = (d >> 8) & 0xFF;
        let db = d & 0xFF;
        let oa = sa + da * ia / 255;
        let or_ = (r as u32 * sa / 255) + dr * ia / 255;
        let og = (g as u32 * sa / 255) + dg * ia / 255;
        let ob = (b as u32 * sa / 255) + db * ia / 255;
        self.px[i] = ((oa.min(255)) << 24) | ((or_.min(255)) << 16) | ((og.min(255)) << 8) | ob.min(255);
    }

    pub fn rect(&mut self, x: i32, y: i32, w: i32, h: i32, r: u8, g: u8, b: u8, a: u8) {
        for j in 0..h { for i in 0..w { self.blend(x + i, y + j, r, g, b, a); } }
    }

    pub fn frame(&mut self, x: i32, y: i32, w: i32, h: i32, r: u8, g: u8, b: u8, a: u8) {
        for i in 0..w { self.blend(x + i, y, r, g, b, a); self.blend(x + i, y + h - 1, r, g, b, a); }
        for j in 0..h { self.blend(x, y + j, r, g, b, a); self.blend(x + w - 1, y + j, r, g, b, a); }
    }

    pub fn line(&mut self, mut x0: i32, mut y0: i32, x1: i32, y1: i32, r: u8, g: u8, b: u8, a: u8) {
        let dx = (x1 - x0).abs();
        let sx = if x0 < x1 { 1 } else { -1 };
        let dy = -(y1 - y0).abs();
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;
        loop {
            self.blend(x0, y0, r, g, b, a);
            if x0 == x1 && y0 == y1 { break; }
            let e2 = 2 * err;
            if e2 >= dy { err += dy; x0 += sx; }
            if e2 <= dx { err += dx; y0 += sy; }
        }
    }

    pub fn text(&mut self, x: i32, y: i32, s: &str, r: u8, g: u8, b: u8, a: u8, sc: i32) {
        let sc = sc.max(1);
        let mut cx = x;
        for ch in s.bytes() {
            let gi = if ch >= 32 && ch < 128 { (ch - 32) as usize } else { 0 };
            let gl = FONT[gi];
            for col in 0..5usize {
                let bits = gl[col];
                for row in 0..7usize {
                    if bits & (1u8 << row) != 0 {
                        for dy in 0..sc { for dx in 0..sc {
                            self.blend(cx + col as i32 * sc + dx, y + row as i32 * sc + dy, r, g, b, a);
                        } }
                    }
                }
            }
            cx += 6 * sc;
        }
    }

    pub fn tw(&self, s: &str, sc: i32) -> i32 { s.len() as i32 * 6 * sc.max(1) }
    pub fn th(&self, sc: i32) -> i32 { 7 * sc.max(1) }
}
